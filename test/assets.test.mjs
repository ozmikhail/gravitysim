import assert from "node:assert/strict";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";

import { assetsFor, checkAssets, CLANG_FORMAT, syncAssets } from "../src/assets.mjs";

function fixture(verify) {
  const root = mkdtempSync(join(process.cwd(), ".plumb-asset-test-"));
  try { verify(root); } finally { rmSync(root, { recursive: true, force: true }); }
}

test("sync is idempotent and content drift fails", () => {
  fixture((root) => {
    const config = { preset: "ozlabs" };
    assert.equal(syncAssets({ root, config }).diagnostics.length, 0);
    assert.deepEqual(checkAssets({ root, config }), []);
    assert.deepEqual(syncAssets({ root, config }), { written: [], diagnostics: [] });
    writeFileSync(join(root, ".editorconfig"), "# generated by @ozlabs/plumb; old\nwrong\n");
    assert.equal(checkAssets({ root, config })[0].rule, "generated.drift");
    assert.deepEqual(syncAssets({ root, config }).written, [".editorconfig"]);
    assert.deepEqual(checkAssets({ root, config }), []);
  });
});

test("unchanged generated bytes do not conceal or preserve a missing executable mode", { skip: process.platform === "win32" }, () => {
  fixture((root) => {
    const config = { preset: "portable", generated: [{ path: "bin/run.sh", content: "#!/bin/sh\n# generated by @ozlabs/plumb; do not edit\n", executable: true }] };
    syncAssets({ root, config });
    chmodSync(join(root, "bin/run.sh"), 0o644);
    assert.equal(checkAssets({ root, config })[0].rule, "generated.mode");
    assert.deepEqual(syncAssets({ root, config }).written, ["bin/run.sh"]);
    assert.equal(statSync(join(root, "bin/run.sh")).mode & 0o111, 0o111);
  });
});

test("unrelated assets block the complete sync before any file changes", () => {
  fixture((root) => {
    const config = { preset: "ozlabs" };
    writeFileSync(join(root, ".editorconfig"), "root = true\n");
    const result = syncAssets({ root, config });
    assert.deepEqual(result.written, []);
    assert.equal(result.diagnostics[0].rule, "generated.ownership");
    assert.equal(readFileSync(join(root, ".editorconfig"), "utf8"), "root = true\n");
  });
});

test("v0.4 generated assets upgrade without an adoption override", () => {
  fixture((root) => {
    writeFileSync(join(root, ".editorconfig"), "# generated by @ozlabs/plumb; change plumb.config.ts, then run plumb sync\nold\n");
    const config = { preset: "ozlabs" };
    assert.equal(syncAssets({ root, config }).diagnostics.length, 0);
    assert.deepEqual(checkAssets({ root, config }), []);
  });
});

test("native profiles generate configs in their own project roots", () => {
  const config = { preset: "portable", projects: [{ root: "ruby", profile: "ruby" }, { root: ".", profile: "cpp" }] };
  const assets = assetsFor(config);
  assert.deepEqual(assets.map(({ path }) => path), [".clang-format", ".clang-format-ignore", ".clang-tidy", "ruby/.rubocop.yml"]);
  assert.ok(assets.find(({ path }) => path === "ruby/.rubocop.yml").content.includes("EnabledByDefault: true"));
  assert.ok(assets.find(({ path }) => path === ".clang-tidy").content.includes('WarningsAsErrors: "*"'));
  const format = JSON.parse(assets.find(({ path }) => path === ".clang-format").content.split("\n").slice(1).join("\n"));
  assert.deepEqual(format, CLANG_FORMAT);
  assert.equal(format.SortIncludes, "CaseSensitive");
  assert.equal(format.IncludeBlocks, "Regroup");
  assert.equal(format.InsertBraces, true);
  assert.equal(existsSync(new URL("../src/assets/clang-format.yml", import.meta.url)), false, "clang-format policy must have one source of truth");
  fixture((root) => {
    syncAssets({ root, config });
    rmSync(join(root, ".clang-format-ignore"));
    assert.deepEqual(checkAssets({ root, config }).map(({ rule, path }) => [rule, path]), [["generated.drift", ".clang-format-ignore"]]);
  });
});

test("custom generated data cannot replace preset-owned files", () => {
  assert.throws(() => assetsFor({ preset: "ozlabs", generated: [{ path: ".editorconfig", content: "weaker" }] }), /cannot replace/);
  assert.throws(() => assetsFor({ preset: "ozlabs", generated: [{ path: "./.editorconfig", content: "weaker" }] }), /cannot replace/);
  assert.throws(() => assetsFor({ preset: "portable", generated: [{ path: "src/a.json", content: "{}" }, { path: "src\\a.json", content: "[]" }] }), /duplicate/);
  fixture((root) => {
    const config = { preset: "portable", generated: [{ path: "config/settings.json", content: '{"version":1}\n' }] };
    assert.deepEqual(syncAssets({ root, config }).written, ["config/settings.json"]);
    assert.deepEqual(checkAssets({ root, config }), []);
    const updated = { ...config, generated: [{ path: "config/settings.json", content: '{"version":2}\n' }] };
    assert.deepEqual(syncAssets({ root, config: updated }).written, ["config/settings.json"]);
    assert.equal(readFileSync(join(root, "config/settings.json"), "utf8"), '{"version":2}\n');
  });
});

test("conflicting generated file and directory paths fail before sync writes", () => {
  fixture((root) => {
    const config = { preset: "portable", generated: [{ path: "output", content: "first" }, { path: "output/data.json", content: "{}" }] };
    assert.throws(() => syncAssets({ root, config }), /generated file cannot also be a directory/);
    assert.equal(existsSync(join(root, "output")), false);
    assert.throws(() => assetsFor({ preset: "portable", projects: [{ root: "native", profile: "cpp" }], generated: [{ path: "native", content: "first" }] }), /generated file cannot also be a directory/);
  });
});

test("generated paths reject symlink parents and never touch their target", { skip: process.platform === "win32" }, () => {
  fixture((root) => {
    mkdirSync(join(root, "real"));
    symlinkSync(join(root, "real"), join(root, "linked"), "dir");
    const config = { preset: "portable", generated: [{ path: "linked/out.txt", content: "new" }] };
    const result = syncAssets({ root, config });
    assert.deepEqual(result.written, []);
    assert.equal(result.diagnostics[0].status, "incomplete");
    assert.equal(existsSync(join(root, "real/out.txt")), false);
  });
});
